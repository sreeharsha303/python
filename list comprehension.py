# from an existing iterable such as a list, tuple, or range.

#syntax : new_list = [expression for item in iterable ]
#expression : what  you want to store inside the new list
#item : each element in the iterable
#iterable : a sequence of elements that can be iterated over (e.g., a list, tuple, or range)





